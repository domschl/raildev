void EuropeProjection::latLonToWorld(double lat, double lon, double& outX, double& outY) {
    const double u = (lon - kMinLon) / (kMaxLon - kMinLon);
    const double v = (kMaxLat - lat) / (kMaxLat - kMinLat);
    outX = u * kWorldWidth;
    outY = v * kWorldHeight;
}

void EuropeProjection::worldToLatLon(double worldX, double worldY, double& outLat, double& outLon) {
    const double u = worldX / kWorldWidth;
    const double v = worldY / kWorldHeight;
    outLon = kMinLon + u * (kMaxLon - kMinLon);
    outLat = kMaxLat - v * (kMaxLat - kMinLat);
}

